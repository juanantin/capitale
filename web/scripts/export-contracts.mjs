// Copies ABIs (and bytecode for the contracts the browser deploys) from the Foundry build
// (../out) into lib/abis.ts and lib/bytecode.ts. Run after `forge build`:
//   node scripts/export-contracts.mjs
import { readFileSync, writeFileSync } from "node:fs";

const out = (file, name) => JSON.parse(readFileSync(new URL(`../../out/${file}/${name}.json`, import.meta.url), "utf8"));
const abis = {
  vaultAbi: out("CapitaleVault.sol", "CapitaleVault"),
  nftAbi: out("CapitaleNFT.sol", "CapitaleNFT"),
  pricingAbi: out("CapitalePricing.sol", "CapitalePricing"),
  testKitAbi: out("TestKit.sol", "TestKit"),
  testTokenAbi: out("TestKit.sol", "TestToken"),
  testOracleAbi: out("TestKit.sol", "TestOracle"),
  testAdapterAbi: out("TestKit.sol", "TestSwapAdapter"),
};
let a = "// Generated by scripts/export-contracts.mjs from the Foundry build. Do not edit.\n\n";
for (const [k, v] of Object.entries(abis)) a += `export const ${k} = ${JSON.stringify(v.abi)} as const;\n\n`;
writeFileSync(new URL("../lib/abis.ts", import.meta.url), a);

let b = "// Generated by scripts/export-contracts.mjs from the Foundry build. Do not edit.\n\n";
for (const [k, v] of Object.entries({ vault: abis.vaultAbi, nft: abis.nftAbi, pricing: abis.pricingAbi, testKit: abis.testKitAbi })) {
  b += `export const ${k}Bytecode = "${v.bytecode.object}" as const;\n`;
}
writeFileSync(new URL("../lib/bytecode.ts", import.meta.url), b);
console.log("exported abis.ts and bytecode.ts");
